// Ставится после первой отрисовки в браузере. До этого (серверная разметка и её гидратация) — false,
// поэтому классы на сервере и в браузере совпадают.
let mounted = false;

/** Приложение уже ожило в браузере: всё, что рисуется дальше, — переходы внутри сайта, а не первая загрузка. */
export function markAppMounted(): void {
  mounted = true;
}

/**
 * Экран открыт переходом внутри сайта, а не по прямой ссылке. Анимации появления экранов играем только
 * при переходе — при загрузке страницы экран просто на месте.
 */
export function isClientNavigation(): boolean {
  return mounted;
}
