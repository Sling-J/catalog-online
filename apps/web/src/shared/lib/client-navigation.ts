// Ставится при первом переходе внутри сайта. До этого (серверная разметка и её гидратация) — false,
// поэтому классы на сервере и в браузере совпадают. Не после первой отрисовки корня: страницы маршрутов
// гидратируются позже корня (ленивые чанки), и экран товара по прямой ссылке получал бы классы анимации.
let mounted = false;

/** Начался переход внутри сайта: всё, что рисуется дальше, — переходы, а не первая загрузка. */
export function markAppMounted(): void {
  mounted = true;
}

/**
 * Экран открыт переходом внутри сайта, а не по прямой ссылке. Анимации появления экранов играем только
 * при переходе — при загрузке страницы экран просто на месте.
 */
export function isClientNavigation(): boolean {
  return mounted;
}
